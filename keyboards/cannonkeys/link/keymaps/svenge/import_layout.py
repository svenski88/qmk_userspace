"""Import the six-layer Link VIA matrix; reserve the right encoder for screen mode."""
import argparse
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "link.layout.json"
OUTPUT = HERE / "layout.inc"


def generate(data):
    if data.get("vendorProductId") != (0xCA04 << 16 | 0x0038):
        raise ValueError("Expected CannonKeys Link VIA export (CA04:0038)")
    if any(data.get("macros", [])) or data.get("encoders"):
        raise ValueError("Nonempty macros/encoder maps need an explicit migration")
    layers = data.get("layers", [])
    if len(layers) != 6 or any(len(layer) != 60 for layer in layers):
        raise ValueError("Expected six 10x6 electrical-matrix layers")
    lines = [
        "// Copyright 2026 svenski88",
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Generated by this keymap's import_layout.py from link.layout.json.",
        "// Only matrix [9,5], the right encoder push, is replaced by LINK_DISPLAY.",
        "// clang-format off",
        "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {",
    ]
    for number, layer in enumerate(layers):
        codes = []
        for code in layer:
            if not isinstance(code, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]*(?:\([A-Z0-9_, ]+\))?", code):
                raise ValueError(f"Unsupported keycode in layer {number}: {code!r}")
            codes.append("QK_BOOT" if code == "RESET" else code)
        codes[9 * 6 + 5] = "LINK_DISPLAY"
        lines.append(f"    [{number}] = {{")
        for row in range(10):
            lines.append("        { " + ", ".join(f"{code:<15}" for code in codes[row * 6:(row + 1) * 6]) + " },")
        lines.append("    },")
    return "\n".join(lines + ["};", "// clang-format on", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "Compiled Link layout is stale; run this script without --check\n")
        print("PASS: 360 Link matrix entries match the VIA export with the documented encoder override")
    else:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT}")


if __name__ == "__main__":
    main()
